using System.Text.Json;
using Statventure.Graphics;
using Statventure.Imaging;
using Statventure.Tests.Canvas;
using Statventure.Tests.Infrastructure;
using Statventure.UI.Dom;
using Statventure.UI.Paint;
using CanvasRenderer = Statventure.Canvas.Canvas;

namespace Statventure.Tests.Ui;

/// <summary>
/// The paint fixtures must look as the game's browser paints them (Golden/ui-*.png, made by
/// Tools/Scripts/make-paint-references.sh).
/// </summary>
[Collection("GPU")]
public class PaintReferenceTests(GpuFixture gpu)
{
    public static TheoryData<string> Fixtures => new(PaintFixtures.All.Select(f => f.Name));

    static string ReferenceDirectory => Path.Combine(Path.GetDirectoryName(Golden.GoldenPath("x"))!, "..", "Reference");

    [Fact]
    public void TheBrowserScriptIsUpToDate()
    {
        var path = Path.Combine(ReferenceDirectory, "paint-fixtures.js");
        var script = ExportScript();
        if (!File.Exists(path) || File.ReadAllText(path) != script)
            File.WriteAllText(path, script);
        Assert.Contains("statventurePaintFixtures", script);
    }

    /// <summary>A fixture as the engine shows it: laid out, scrolled as its data attributes say.</summary>
    /// <param name="pageZoom">A page zoom on top of the device scale; the fixture keeps its size in CSS px (the references lay it out in an iframe that size).</param>
    /// <param name="prepare">Called on the new document before anything is laid out (the image sizes a fixture's images need).</param>
    public static UiDocument Build(PaintFixture fixture, float deviceScale = 1, float pageZoom = 1, Action<UiDocument>? prepare = null)
    {
        var document = new UiDocument(TestFonts.Library);
        prepare?.Invoke(document);
        document.SetViewport(fixture.Width * pageZoom, fixture.Height * pageZoom);
        document.SetZoom(deviceScale, pageZoom);
        document.AddStylesheet(LayoutFixtures.BaseCss + fixture.Css, fixture.Name);
        Markup.SetInnerHtml(document.Body, fixture.Html);
        document.Update(0);
        foreach (var element in document.AllElements().ToList())
        {
            if (float.TryParse(element.GetAttribute("data-scroll-left"), out var left))
                element.ScrollLeft = left;
            if (float.TryParse(element.GetAttribute("data-scroll-top"), out var top))
                element.ScrollTop = top;
            if (element.HasAttribute("data-indeterminate"))
                element.Indeterminate = true;
            if (element.HasAttribute("data-focus"))
                element.Focus();
        }
        document.ScrollPosition = new System.Numerics.Vector2(fixture.ScrollX, fixture.ScrollY);
        if (!fixture.WindowFocused)
            document.Input.WindowBlur();
        document.Update(0);
        return document;
    }

    [Theory]
    [MemberData(nameof(Fixtures))]
    public void TheFixturePaintsLikeTheBrowser(string name)
    {
        var fixture = PaintFixtures.All.Single(f => f.Name == name);
        var document = Build(fixture);
        Golden.Match("ui-" + name, Render(gpu.Device, document, fixture.Width, fixture.Height), tolerance: fixture.Tolerance, maxDifferentRatio: 0.002);
    }

    public static RgbaImage Render(GpuDevice device, UiDocument document, int width, int height)
    {
        using var painter = new UiPainter(document);
        using var canvas = new CanvasRenderer(device);
        using var target = GpuImage.CreateRenderTarget(device, width, height);
        var frame = device.BeginFrame();
        canvas.Begin(width, height);
        painter.Paint(canvas);
        canvas.Render(frame, target);
        device.EndFrame(frame);
        device.WaitIdle();
        return new RgbaImage(width, height, target.ReadPixels());
    }

    public static string ExportScript()
    {
        var fixtures = PaintFixtures.All.Select(f => new { name = f.Name, width = f.Width, height = f.Height, css = LayoutFixtures.BaseCss + f.Css, html = f.Html, scrollX = f.ScrollX, scrollY = f.ScrollY });
        return "// Generated by Statventure.Tests (PaintReferenceTests.ExportScript): screenshots the paint fixtures.\n"
            + "const STATVENTURE_PAINT_FIXTURES = " + JsonSerializer.Serialize(fixtures) + ";\n" + """
            async function statventurePaintFixtures() {
              const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
              const base = new URL(".", location.href).href;
              const fonts = `@font-face { font-family: Lato; src: url("${base}objects/fonts/Lato-Regular.ttf"); font-weight: 400; }`;
              for (const fixture of STATVENTURE_PAINT_FIXTURES) {
                const frame = document.createElement("iframe");
                frame.style.cssText = `position:fixed;left:0;top:0;width:${fixture.width}px;height:${fixture.height}px;border:0;z-index:2147483647;background:#fff`;
                const loaded = new Promise(resolve => frame.onload = resolve);
                frame.srcdoc = `<!DOCTYPE html><html><head><style>${fonts}\n${fixture.css}</style></head><body>${fixture.html}</body></html>`;
                document.body.append(frame);
                await loaded;
                const doc = frame.contentDocument;
                for (const el of doc.querySelectorAll("[data-scroll-left], [data-scroll-top]")) {
                  if (el.dataset.scrollLeft) el.scrollLeft = Number(el.dataset.scrollLeft);
                  if (el.dataset.scrollTop) el.scrollTop = Number(el.dataset.scrollTop);
                }
                for (const el of doc.querySelectorAll("[data-indeterminate]")) el.indeterminate = true;
                for (const el of doc.querySelectorAll("[data-focus]")) el.focus();
                frame.contentWindow.scrollTo(fixture.scrollX, fixture.scrollY);
                await wait(400);
                await window.statFickDesktop.captureTestScreen("ui-" + fixture.name, 1600, 900);
                frame.remove();
              }
            }
            """;
    }
}
