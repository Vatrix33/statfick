using Brutal.VulkanApi;
using Brutal.VulkanApi.Vma;

namespace Statventure.Graphics;

public sealed record ImageDesc
{
    public required int Width { get; init; }
    public required int Height { get; init; }
    public VkFormat Format { get; init; } = VkFormat.R8G8B8A8UNorm;
    public int MipLevels { get; init; } = 1;
    public VkImageUsageFlags Usage { get; init; } = VkImageUsageFlags.SampledBit | VkImageUsageFlags.TransferDstBit;
    public VkSampleCountFlags Samples { get; init; } = VkSampleCountFlags._1Bit;
    /// <summary>Register in the bindless table so shaders can sample it by index.</summary>
    public bool Bindless { get; init; } = true;
}

/// <summary>
/// A 2D Vulkan image with its view. It tracks its own layout, so command lists insert the right
/// barriers; sampled images get an index in the bindless texture table.
/// </summary>
public sealed unsafe class GpuImage : IDisposable
{
    readonly GpuDevice _device;
    readonly VmaAllocation _allocation;
    readonly bool _owned;
    bool _disposed;

    public VkImage Handle { get; }
    public VkImageView View { get; }
    public VkFormat Format { get; }
    public int Width { get; }
    public int Height { get; }
    public int MipLevels { get; }
    public VkImageUsageFlags Usage { get; }
    public VkSampleCountFlags Samples { get; }
    public VkImageAspectFlags Aspect { get; }
    /// <summary>The layout of every subresource, as far as recorded commands go.</summary>
    public VkImageLayout Layout { get; internal set; }
    /// <summary>Index in the bindless texture table, or -1.</summary>
    public int BindlessIndex { get; private set; } = -1;

    GpuImage(GpuDevice device, VkImage handle, VkImageView view, VmaAllocation allocation, bool owned, VkFormat format, int width, int height, int mips, VkImageUsageFlags usage, VkSampleCountFlags samples)
    {
        _device = device;
        Handle = handle;
        View = view;
        _allocation = allocation;
        _owned = owned;
        Format = format;
        Width = width;
        Height = height;
        MipLevels = mips;
        Usage = usage;
        Samples = samples;
        Aspect = Formats.IsDepth(format) ? VkImageAspectFlags.DepthBit : VkImageAspectFlags.ColorBit;
        Layout = VkImageLayout.Undefined;
    }

    public static GpuImage Create(GpuDevice device, ImageDesc desc)
    {
        var info = new VkImageCreateInfo
        {
            ImageType = VkImageType._2D,
            Format = desc.Format,
            Extent = new VkExtent3D { Width = desc.Width, Height = desc.Height, Depth = 1 },
            MipLevels = desc.MipLevels,
            ArrayLayers = 1,
            Samples = desc.Samples,
            Tiling = VkImageTiling.Optimal,
            Usage = desc.Usage,
            SharingMode = VkSharingMode.Exclusive,
            InitialLayout = VkImageLayout.Undefined,
        };
        var allocation = new VmaAllocationCreateInfo { Usage = VmaMemoryUsage.AutoPreferDevice };
        var result = device.Allocator.CreateImage(info, allocation, out var image, out var vmaAllocation, out _);
        if (result != VkResult.Success)
            throw new InvalidOperationException($"image {desc.Width}x{desc.Height} {desc.Format} could not be created: {result}");
        var aspect = Formats.IsDepth(desc.Format) ? VkImageAspectFlags.DepthBit : VkImageAspectFlags.ColorBit;
        var view = device.Device.CreateImageView(new VkImageViewCreateInfo
        {
            Image = image,
            ViewType = VkImageViewType._2D,
            Format = desc.Format,
            SubresourceRange = new VkImageSubresourceRange { AspectMask = aspect, LevelCount = desc.MipLevels, LayerCount = 1 },
        }, null);
        var created = new GpuImage(device, image, view, vmaAllocation, true, desc.Format, desc.Width, desc.Height, desc.MipLevels, desc.Usage, desc.Samples);
        if (desc.Bindless && desc.Usage.HasFlag(VkImageUsageFlags.SampledBit))
            created.BindlessIndex = device.Bindless.Register(view);
        return created;
    }

    /// <summary>A sampled texture from tightly packed pixels; mip levels are generated by blitting.</summary>
    public static GpuImage CreateTexture(GpuDevice device, int width, int height, ReadOnlySpan<byte> pixels, VkFormat format = VkFormat.R8G8B8A8UNorm, bool mipmaps = false)
    {
        var mips = mipmaps ? MipCount(width, height) : 1;
        var image = Create(device, new ImageDesc
        {
            Width = width,
            Height = height,
            Format = format,
            MipLevels = mips,
            Usage = VkImageUsageFlags.SampledBit | VkImageUsageFlags.TransferDstBit | VkImageUsageFlags.TransferSrcBit,
        });
        image.Upload(pixels);
        return image;
    }

    /// <summary>A colour target that can also be sampled and read back.</summary>
    public static GpuImage CreateRenderTarget(GpuDevice device, int width, int height, VkFormat format = VkFormat.R8G8B8A8UNorm, VkSampleCountFlags samples = VkSampleCountFlags._1Bit)
    {
        var usage = VkImageUsageFlags.ColorAttachmentBit | VkImageUsageFlags.TransferSrcBit | VkImageUsageFlags.TransferDstBit;
        if (samples == VkSampleCountFlags._1Bit)
            usage |= VkImageUsageFlags.SampledBit;
        return Create(device, new ImageDesc { Width = width, Height = height, Format = format, Usage = usage, Samples = samples });
    }

    public static GpuImage CreateDepth(GpuDevice device, int width, int height, VkFormat format = VkFormat.D32SFloat, VkSampleCountFlags samples = VkSampleCountFlags._1Bit, bool sampled = false)
    {
        var usage = VkImageUsageFlags.DepthStencilAttachmentBit;
        if (sampled)
            usage |= VkImageUsageFlags.SampledBit;
        return Create(device, new ImageDesc { Width = width, Height = height, Format = format, Usage = usage, Samples = samples, Bindless = sampled });
    }

    /// <summary>Wraps an image owned by someone else (a swapchain image).</summary>
    internal static GpuImage Wrap(GpuDevice device, VkImage image, VkImageView view, VkFormat format, int width, int height, VkImageUsageFlags usage) =>
        new(device, image, view, default, false, format, width, height, 1, usage, VkSampleCountFlags._1Bit);

    public static int MipCount(int width, int height) => 1 + (int)Math.Floor(Math.Log2(Math.Max(1, Math.Max(width, height))));

    /// <summary>Uploads mip level 0 (tightly packed), regenerates the other levels and leaves the image ready to sample.</summary>
    public void Upload(ReadOnlySpan<byte> pixels)
    {
        var expected = (long)Width * Height * Formats.BytesPerPixel(Format);
        if (pixels.Length != expected)
            throw new ArgumentException($"expected {expected} bytes for {Width}x{Height} {Format}, got {pixels.Length}");
        using var staging = GpuBuffer.Create(_device, (ulong)pixels.Length, 0, MemoryKind.Upload);
        staging.Write(pixels);
        _device.Immediate(commands =>
        {
            commands.Transition(this, VkImageLayout.TransferDstOptimal);
            commands.CopyBufferToImage(staging, this, 0);
            if (MipLevels > 1)
                commands.GenerateMipmaps(this);
            commands.Transition(this, VkImageLayout.ShaderReadOnlyOptimal);
        });
    }

    /// <summary>Copies mip level 0 back to the CPU as RGBA8 (BGRA formats are swizzled). Waits for the GPU.</summary>
    public byte[] ReadPixels()
    {
        var bytesPerPixel = Formats.BytesPerPixel(Format);
        var size = (ulong)((long)Width * Height * bytesPerPixel);
        using var readback = GpuBuffer.Create(_device, size, 0, MemoryKind.Readback);
        _device.Immediate(commands =>
        {
            var previous = Layout == VkImageLayout.Undefined ? VkImageLayout.ShaderReadOnlyOptimal : Layout;
            commands.Transition(this, VkImageLayout.TransferSrcOptimal);
            commands.CopyImageToBuffer(this, readback, 0);
            commands.Transition(this, previous);
        });
        var pixels = new byte[size];
        readback.Read<byte>(pixels);
        if (Formats.IsBgra(Format))
            for (var i = 0; i < pixels.Length; i += 4)
                (pixels[i], pixels[i + 2]) = (pixels[i + 2], pixels[i]);
        return pixels;
    }

    public void Dispose()
    {
        if (_disposed)
            return;
        _disposed = true;
        if (BindlessIndex >= 0)
        {
            var (bindless, index) = (_device.Bindless, BindlessIndex);
            _device.Release(() => bindless.Unregister(index));
        }
        if (!_owned)
            return;
        var (device, allocator, handle, view, allocation) = (_device.Device, _device.Allocator, Handle, View, _allocation);
        _device.Release(() =>
        {
            device.DestroyImageView(view, null);
            allocator.DestroyImage(handle, allocation);
        });
    }
}

public static class Formats
{
    public static bool IsDepth(VkFormat format) =>
        format is VkFormat.D32SFloat or VkFormat.D16UNorm or VkFormat.D24UNormS8UInt or VkFormat.D32SFloatS8UInt;

    public static bool IsBgra(VkFormat format) => format is VkFormat.B8G8R8A8UNorm or VkFormat.B8G8R8A8SRGB;

    /// <summary>Unsigned or signed integer colour formats (an MSAA resolve can only take one sample of these).</summary>
    public static bool IsInteger(VkFormat format) =>
        format is VkFormat.R8UInt or VkFormat.R16UInt or VkFormat.R32UInt or VkFormat.R32G32UInt or VkFormat.R32G32B32A32UInt
            or VkFormat.R8SInt or VkFormat.R16SInt or VkFormat.R32SInt or VkFormat.R32G32SInt or VkFormat.R32G32B32A32SInt;

    public static int BytesPerPixel(VkFormat format) => format switch
    {
        VkFormat.R8UNorm or VkFormat.R8UInt => 1,
        VkFormat.R16UInt => 2,
        VkFormat.R8G8UNorm => 2,
        VkFormat.R16G16B16A16SFloat or VkFormat.R32G32UInt => 8,
        VkFormat.R32G32B32A32SFloat => 16,
        VkFormat.R16SFloat => 2,
        VkFormat.R32SFloat => 4,
        _ => 4,
    };
}
