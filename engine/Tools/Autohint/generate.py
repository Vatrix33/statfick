#!/usr/bin/env python3
"""Converts skrifa's generated autohinter style data (skrifa/generated/generated_autohint_styles.rs,
skrifa 0.44.0, the version Chromium 152 builds) into Engine/Statventure/Text/Autohint/StyleData.g.cs.

Usage: generate.py path/to/generated_autohint_styles.rs"""
import re, sys, os

src = open(sys.argv[1], encoding="utf-8").read()
out = os.path.join(os.path.dirname(__file__), "..", "..", "Engine", "Statventure", "Text", "Autohint", "StyleData.g.cs")

def unescape(s):
    return re.sub(r"\\u\{([0-9a-fA-F]+)\}", lambda m: chr(int(m.group(1), 16)), s)

def cs_string(s):
    s = unescape(s)
    r = []
    for ch in s:
        o = ord(ch)
        if ch == '"' or ch == '\\':
            r.append('\\' + ch)
        elif o < 0x20 or 0x200b <= o <= 0x200f or o == 0xfeff:
            r.append('\\u%04x' % o)
        else:
            r.append(ch)
    return '"' + ''.join(r) + '"'

zones = {"NONE": "None", "TOP": "Top", "SUB_TOP": "SubTop", "NEUTRAL": "Neutral", "ADJUSTMENT": "Adjustment",
         "X_HEIGHT": "XHeight", "LONG": "Long", "HORIZONTAL": "Horizontal", "RIGHT": "Right"}

def cs_zones(expr):
    names = re.findall(r"BlueZones::([A-Z_]+)", expr)
    return " | ".join("BlueZones." + zones[n] for n in names)

scripts_src = src[src.index("pub const SCRIPT_CLASSES"):]
scripts_src = scripts_src[:scripts_src.index("\n];")]
script_re = re.compile(r'ScriptClass \{\s*name: "([^"]*)",\s*group: ScriptGroup::(\w+),\s*tag: Tag::new\(b"(....)"\),\s*hint_top_to_bottom: (true|false),\s*std_chars: "((?:[^"\\]|\\.)*)",\s*blues: &\[(.*?)\],\s*\},', re.S)
blue_re = re.compile(r'\("((?:[^"\\]|\\.)*)", (BlueZones::[A-Z_]+(?:\.union\(BlueZones::[A-Z_]+\))*)\)')
scripts = []
for m in script_re.finditer(scripts_src):
    blues = [(b.group(1), cs_zones(b.group(2))) for b in blue_re.finditer(m.group(6))]
    scripts.append((m.group(1), m.group(2), m.group(3), m.group(4), m.group(5), blues))

def consts(block_start):
    i = src.index(block_start)
    j = src.index("}", i)
    return re.findall(r"pub const (\w+): usize = (\d+);", src[i:j])

script_consts = consts("impl ScriptClass {")
style_consts = consts("impl StyleClass {")
assert len(script_consts) == len(scripts), (len(script_consts), len(scripts))

styles = re.findall(r'StyleClass \{ name: "([^"]*)", index: (\d+), script: &SCRIPT_CLASSES\[(\d+)\], feature: (None|Some\(Tag::new\(b"(....)"\)\)) \}', src)
ranges = re.findall(r"(base_range|non_base_range)\((\d+), (\d+), (\d+)\)", src[src.index("STYLE_RANGES"):])

lines = []
w = lines.append
w("// <auto-generated> by Tools/Autohint/generate.py from skrifa 0.44.0's generated_autohint_styles.rs. Do not edit. </auto-generated>")
w("namespace Statventure.Text.Autohint;")
w("")
w("internal sealed partial class ScriptClass")
w("{")
for name, value in script_consts:
    w(f"    public const int {name.capitalize()} = {value};")
w("")
w("    public static readonly ScriptClass[] All =")
w("    [")
for name, group, tag, top_to_bottom, std_chars, blues in scripts:
    b = ", ".join(f"({cs_string(s)}, {z})" for s, z in blues)
    w(f"        new({cs_string(name)}, ScriptGroup.{group}, \"{tag}\", {top_to_bottom}, {cs_string(std_chars)}, [{b}]),")
w("    ];")
w("}")
w("")
w("internal sealed partial class StyleClass")
w("{")
for name, value in style_consts:
    w(f"    public const int {name.capitalize()} = {value};")
w("")
w("    public static readonly StyleClass[] All =")
w("    [")
for name, index, script, feature, tag in styles:
    f = f'"{tag}"' if tag else "null"
    w(f"        new({cs_string(name)}, {index}, ScriptClass.All[{script}], {f}),")
w("    ];")
w("}")
w("")
w("internal static partial class StyleRanges")
w("{")
w("    public static readonly StyleRange[] All =")
w("    [")
for kind, first, last, style in ranges:
    flag = " | GlyphStyle.NonBase" if kind == "non_base_range" else ""
    w(f"        new({first}, {last}, new GlyphStyle((ushort)({style}{flag}))),")
w("    ];")
w("}")
open(out, "w", encoding="utf-8").write("\n".join(lines) + "\n")
print(f"{len(scripts)} scripts, {len(styles)} styles, {len(ranges)} ranges -> {os.path.normpath(out)}")
