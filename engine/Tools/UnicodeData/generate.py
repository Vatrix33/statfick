#!/usr/bin/env python3
"""Generates Engine/Statventure/Text/WordBreakData.g.cs and CharacterProperties.g.cs from the Unicode 17 character database
(the version of ICU 78, which Chromium 152 uses): each code point's word-break class as ICU's
word rules (data/brkitr/rules/word.txt) define their sets, and the Extended_Pictographic and
Kana/Kanji flags those rules use.

Also, for Blink's backspace rules: Variation_Selector, Emoji_Modifier_Base, a non-zero
canonical combining class and Extended_Pictographic; and where text decorations don't skip ink.

Usage: generate.py <ucd directory> <output directory>
The directory needs WordBreakProperty.txt, emoji-data.txt, Scripts.txt, PropList.txt,
LineBreak.txt, GraphemeBreakProperty.txt, UnicodeData.txt and Blocks.txt from
https://www.unicode.org/Public/17.0.0/ucd/ (auxiliary/ and emoji/ files included), and
emoji-sequences.txt and emoji-zwj-sequences.txt from https://www.unicode.org/Public/17.0.0/emoji/.
"""
import os
import re
import sys

ucd, output_directory = sys.argv[1], sys.argv[2]
output = os.path.join(output_directory, "WordBreakData.g.cs")
MAX = 0x110000


def load(name, wanted=None):
    """{property value: set of code points} from a UCD file."""
    values = {}
    for line in open(os.path.join(ucd, name), encoding="utf-8"):
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        cps, value = [p.strip() for p in line.split(";")[:2]]
        if wanted is not None and value not in wanted:
            continue
        if ".." in cps:
            a, b = cps.split("..")
            r = range(int(a, 16), int(b, 16) + 1)
        else:
            r = [int(cps, 16)]
        values.setdefault(value, set()).update(r)
    return values


wb = load("WordBreakProperty.txt")
ext_pict = load("emoji-data.txt", {"Extended_Pictographic"})["Extended_Pictographic"]
scripts = load("Scripts.txt", {"Han", "Hiragana"})
han, hiragana = scripts["Han"], scripts["Hiragana"]
ideographic = load("PropList.txt", {"Ideographic"})["Ideographic"]
complex_context = load("LineBreak.txt", {"SA"})["SA"]
gcb_control = load("GraphemeBreakProperty.txt", {"Control"})["Control"]


def prop(name):
    return wb.get(name, set())


# ICU word.txt sets.
katakana = prop("Katakana")
hangul = set(range(0xAC00, 0xD7A4))
kana_kanji = han | hiragana | katakana
dictionary_cjk = kana_kanji | hangul
extend = prop("Extend") - han
classes = [
    # (class, set) in order: the first that holds wins.
    ("CR", prop("CR")),
    ("LF", prop("LF")),
    ("Newline", prop("Newline")),
    ("Extend", extend),
    ("ZWJ", prop("ZWJ")),
    ("RegionalIndicator", prop("Regional_Indicator")),
    ("Format", prop("Format")),
    ("Katakana", katakana),
    ("HebrewLetter", prop("Hebrew_Letter")),
    ("HangulSyllable", hangul),
    ("ALetter", (prop("ALetter") - dictionary_cjk) | (complex_context - extend - gcb_control)),
    ("SingleQuote", prop("Single_Quote")),
    ("DoubleQuote", prop("Double_Quote")),
    ("MidNumLet", prop("MidNumLet") - {0x2E, 0xFF0E}),
    ("MidLetter", prop("MidLetter") - {0x3A, 0xFE55, 0xFF1A}),
    ("MidNum", prop("MidNum") | {0x2E, 0xFF0E}),
    ("Numeric", prop("Numeric")),
    ("ExtendNumLet", prop("ExtendNumLet")),
    ("WSegSpace", prop("WSegSpace")),
    ("Hiragana", hiragana),
    ("Ideographic", ideographic),
]
names = ["Other"] + [c for c, _ in classes]
code = [0] * MAX
for index in range(len(classes) - 1, -1, -1):
    for cp in classes[index][1]:
        code[cp] = index + 1
# Flags: bit 5 Extended_Pictographic, bit 6 Kana/Kanji.
for cp in ext_pict:
    code[cp] |= 32
for cp in kana_kanji:
    code[cp] |= 64

starts, values = [], []
previous = None
for cp in range(MAX):
    if code[cp] != previous:
        starts.append(cp)
        values.append(code[cp])
        previous = code[cp]

lines = []
lines.append("// Generated by Tools/UnicodeData/generate.py from the Unicode 17 character database (ICU 78,")
lines.append("// Chromium 152): word-break classes as ICU's word rules define their sets. Don't edit.")
lines.append("namespace Statventure.Text;")
lines.append("")
lines.append("/// <summary>A code point's class in ICU's word-break rules.</summary>")
lines.append("public enum WordClass : byte")
lines.append("{")
for n in names:
    lines.append(f"    {n},")
lines.append("}")
lines.append("")
lines.append("static partial class WordBreakData")
lines.append("{")
lines.append(f"    /// <summary>The first code point of each run of equal entries ({len(starts)} runs).</summary>")
lines.append("    static readonly int[] Starts =")
lines.append("    [")
for i in range(0, len(starts), 12):
    lines.append("        " + ", ".join(f"0x{s:X}" for s in starts[i:i + 12]) + ",")
lines.append("    ];")
lines.append("")
lines.append("    /// <summary>Each run's class (low 5 bits), Extended_Pictographic (32) and Kana/Kanji (64).</summary>")
lines.append("    static readonly byte[] Values =")
lines.append("    [")
for i in range(0, len(values), 24):
    lines.append("        " + ", ".join(str(v) for v in values[i:i + 24]) + ",")
lines.append("    ];")
lines.append("}")
open(output, "w", encoding="utf-8").write("\n".join(lines) + "\n")
print(f"{len(starts)} runs written to {output}")


# Character properties for the backspace state machine.
variation_selector = load("PropList.txt", {"Variation_Selector"})["Variation_Selector"]
modifier_base = load("emoji-data.txt", {"Emoji_Modifier_Base"})["Emoji_Modifier_Base"]
combining = set()
previous_first = None
for line in open(os.path.join(ucd, "UnicodeData.txt"), encoding="utf-8"):
    fields = line.split(";")
    cp, name, ccc = int(fields[0], 16), fields[1], int(fields[3])
    if name.endswith(", First>"):
        previous_first = cp
        continue
    if name.endswith(", Last>"):
        r = range(previous_first, cp + 1)
    else:
        r = [cp]
    if ccc != 0:
        combining.update(r)
# Where Blink's Character::CanTextDecorationSkipInk is false (underlines don't skip their ink):
# "/", "\\" and "_", CJK ideographs and symbols (character_property_data.h: its array and ranges,
# Emoji_Presentation, and the Extended_Pictographic code points of the RGI emoji ZWJ and modifier
# sequences), and the Hangul and Linear B Ideogram blocks.
CJK_ARRAY = [0x2C7, 0x2CA, 0x2CB, 0x2D9, 0x2020, 0x2021, 0x2030, 0x203B, 0x203C, 0x2042, 0x2047, 0x2048, 0x2049, 0x2051, 0x20DD, 0x20DE, 0x2100, 0x2103, 0x2105, 0x2109, 0x210A, 0x2113, 0x2116, 0x2121, 0x212B, 0x213B, 0x2150, 0x2151, 0x2152, 0x217F, 0x2189, 0x2307, 0x2312, 0x23CE, 0x2423, 0x25A0, 0x25A1, 0x25A2, 0x25AA, 0x25AB, 0x25B1, 0x25B2, 0x25B3, 0x25B6, 0x25B7, 0x25BC, 0x25BD, 0x25C0, 0x25C1, 0x25C6, 0x25C7, 0x25C9, 0x25CB, 0x25CC, 0x25EF, 0x2605, 0x2606, 0x260E, 0x2616, 0x2617, 0x26A0, 0x2713, 0x271A, 0x273F, 0x2740, 0x2756, 0x2763, 0x2B1A, 0xFE10, 0xFE11, 0xFE12, 0xFE19, 0xFF1D, 0x1F100, 0x1F200, 0x1F237, 0x1F32C, 0x1F336, 0x1F37D, 0x1F43F, 0x1F54F, 0x1F93B, 0x1F946]
CJK_RANGES = [(0x2E80, 0x2FDF), (0x31C0, 0x31EF), (0x3400, 0x4DBF), (0x4E00, 0x9FFF), (0xF900, 0xFAFF), (0x20000, 0x2FFFF), (0x2156, 0x215A), (0x2160, 0x216B), (0x2170, 0x217B), (0x23BE, 0x23CC), (0x2460, 0x2492), (0x249C, 0x24FF), (0x25CE, 0x25D3), (0x25E2, 0x25E6), (0x2600, 0x2603), (0x2660, 0x266F), (0x2672, 0x267D), (0x2776, 0x277F), (0x2FF0, 0x302D), (0x3031, 0x312F), (0x3190, 0x31BF), (0x3200, 0x33FF), (0x4DC0, 0x4DFF), (0xF860, 0xF862), (0xFE30, 0xFE6F), (0xFF00, 0xFF0C), (0xFF0E, 0xFF1A), (0xFF1F, 0xFFEF), (0x16FE0, 0x16FFF), (0x17000, 0x187FF), (0x18800, 0x18AFF), (0x1B000, 0x1B0FF), (0x1B100, 0x1B12F), (0x1B170, 0x1B2FF), (0x1F110, 0x1F129), (0x1F130, 0x1F149), (0x1F150, 0x1F169), (0x1F170, 0x1F189), (0x1F202, 0x1F219), (0x1F21B, 0x1F22E), (0x1F230, 0x1F231), (0x1F23B, 0x1F24F), (0x1F252, 0x1F2FF), (0x1F321, 0x1F32A), (0x1F394, 0x1F39F), (0x1F3CD, 0x1F3CE), (0x1F3D4, 0x1F3DF), (0x1F3F1, 0x1F3F2), (0x1F3F5, 0x1F3F7), (0x1F4FD, 0x1F4FE), (0x1F53E, 0x1F54A), (0x1F568, 0x1F573), (0x1F576, 0x1F579), (0x1F57B, 0x1F58F), (0x1F591, 0x1F594), (0x1F597, 0x1F5A3), (0x1F5A5, 0x1F5E7), (0x1F5E9, 0x1F5FA), (0x1F650, 0x1F67F), (0x1F6C6, 0x1F6CB), (0x1F6CD, 0x1F6CF), (0x1F6D3, 0x1F6D4), (0x1F6D9, 0x1F6DB), (0x1F6E0, 0x1F6EA), (0x1F6ED, 0x1F6F3), (0x1F6FD, 0x1F6FF), (0x1F900, 0x1F90B), (0x1FAC9, 0x1FACC)]
cjk = set(CJK_ARRAY)
for a, b in CJK_RANGES:
    cjk.update(range(a, b + 1))
cjk |= load("emoji-data.txt", {"Emoji_Presentation"})["Emoji_Presentation"]


def rgi_sequences(name, wanted):
    """The code points of the emoji sequences of the given types in an emoji/ file."""
    points = set()
    for line in open(os.path.join(ucd, name), encoding="utf-8"):
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        cps, kind = [p.strip() for p in line.split(";")[:2]]
        if kind in wanted and ".." not in cps:
            points.update(int(c, 16) for c in cps.split())
    return points


cjk |= (rgi_sequences("emoji-zwj-sequences.txt", {"RGI_Emoji_ZWJ_Sequence"})
        | rgi_sequences("emoji-sequences.txt", {"RGI_Emoji_Modifier_Sequence"})) & ext_pict
blocks = {}
for line in open(os.path.join(ucd, "Blocks.txt"), encoding="utf-8"):
    line = line.split("#", 1)[0].strip()
    if line:
        span, block = [p.strip() for p in line.split(";")]
        first, last = span.split("..")
        blocks[block] = range(int(first, 16), int(last, 16) + 1)
no_skip_ink = cjk | {0x2F, 0x5C, 0x5F}
for block in ("Hangul Jamo", "Hangul Compatibility Jamo", "Hangul Syllables", "Hangul Jamo Extended-A", "Hangul Jamo Extended-B", "Linear B Ideograms"):
    no_skip_ink.update(blocks[block])

flags = [0] * MAX
for cp in no_skip_ink:
    flags[cp] |= 16
for cp in variation_selector:
    flags[cp] |= 1
for cp in modifier_base:
    flags[cp] |= 2
for cp in combining:
    flags[cp] |= 4
for cp in ext_pict:
    flags[cp] |= 8
starts, values = [], []
previous = None
for cp in range(MAX):
    if flags[cp] != previous:
        starts.append(cp)
        values.append(flags[cp])
        previous = flags[cp]
lines = []
lines.append("// Generated by Tools/UnicodeData/generate.py from the Unicode 17 character database. Don't edit.")
lines.append("namespace Statventure.Text;")
lines.append("")
lines.append("static partial class CharacterProperties")
lines.append("{")
lines.append(f"    /// <summary>The first code point of each run of equal flags ({len(starts)} runs).</summary>")
lines.append("    static readonly int[] Starts =")
lines.append("    [")
for i in range(0, len(starts), 12):
    lines.append("        " + ", ".join(f"0x{v:X}" for v in starts[i:i + 12]) + ",")
lines.append("    ];")
lines.append("")
lines.append("    /// <summary>Variation_Selector (1), Emoji_Modifier_Base (2), non-zero combining class (4), Extended_Pictographic (8), no decoration ink skipping (16).</summary>")
lines.append("    static readonly byte[] Values =")
lines.append("    [")
for i in range(0, len(values), 24):
    lines.append("        " + ", ".join(str(v) for v in values[i:i + 24]) + ",")
lines.append("    ];")
lines.append("}")
path = os.path.join(output_directory, "CharacterProperties.g.cs")
open(path, "w", encoding="utf-8").write("\n".join(lines) + "\n")
print(f"{len(starts)} runs written to {path}")
