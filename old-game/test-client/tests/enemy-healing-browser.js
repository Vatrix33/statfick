async function runEnemyHealingChecks() {
  const assert = (condition, message) => { if (!condition) throw new Error(message); };
  const clone = value => structuredClone(value);
  // Expose deterministic action entry points only inside this isolated test
  // renderer. The production script has no test exports or extra globals.
  Combat.restore(null);
  const source = await (await fetch("scripts/combat.js")).text();
  const marker = "  window.Combat = {";
  assert(source.includes(marker), "Combat test entry point exists");
  const instrumented = source.replace(marker, `
    window.__healingChecks = { actorById, hp, applyEffects, expire,
      applyMeleeSpellEffects, applyAttackHitEffects, useSkill, notifySummonLost,
      startNextPhase, tryRaceDeathSave, evaluateSpellForTarget };
  ` + marker);
  const script = document.createElement("script");
  script.textContent = instrumented;
  document.head.append(script);
  await waitForSourceFiles();
  const hooks = window.__healingChecks;
  const character = defaultCharacter();
  character.raceId = "human"; character.level = 100;
  character.stats.speed = 500;
  character.currentHp = 10000; character.currentMana = 10000;
  applyCharacter(normalizeCharacter(character));
  assert(await Combat.startEncounter(["Goblin"]), "Healing fixture encounter starts");
  document.getElementById("combat-sheet-button").click();
  const template = Combat.serialize();
  const enemyId = template.actors.find(actor => actor.team === "enemy").id;
  assert(template.actors.find(actor => actor.id === enemyId).character.currentHp === template.actors.find(actor => actor.id === enemyId).resourceMax.hp, "Enemies still spawn at full HP");
  template.current = enemyId; template.ap = 10;
  for (const actor of template.actors) actor.resourceMax = { hp: 1000, mana: 1000 };
  const enemyTemplate = template.actors.find(actor => actor.id === enemyId);
  enemyTemplate.character = normalizeCharacter({ ...defaultCharacter(), raceId: "human", level: 100, currentHp: 100, currentMana: 100 });
  enemyTemplate.character.classLevels = {};
  enemyTemplate.effects = []; enemyTemplate.skillExpiry = {};
  const reset = (classes = {}, raceId = "human") => {
    Combat.restore(clone(template));
    currentHp = 100; currentMana = 100;
    classLevels = {}; equipment = defaultCharacter().equipment;
    const enemy = hooks.actorById(enemyId), player = hooks.actorById("player");
    enemy.character.classLevels = classes; enemy.character.raceId = raceId;
    return { enemy, player };
  };
  const heal = (caster, target, amount = 100, maxPercent = 0) => hooks.applyEffects(caster, target, [{ type: "heal", recipient: "target", amount, maxPercent }]);
  let { enemy, player } = reset();
  heal(enemy, enemy);
  assert(hooks.hp(enemy) === 120, "A 100-HP enemy heal restores 20 HP");
  ({ enemy, player } = reset());
  heal(player, enemy);
  assert(hooks.hp(enemy) === 120, "Enemy healing reduction follows the recipient, including friendly-target effects");
  heal(enemy, player);
  assert(currentHp === 200, "Healing received by the player is unchanged regardless of caster team");
  ({ enemy } = reset());
  heal(enemy, enemy, 0, 50);
  assert(hooks.hp(enemy) === 200, "Percentage healing is reduced by 80%");
  ({ enemy } = reset());
  enemy.effects.push({ type: "healing-received-percent", amount: 50, expiresTurn: 10 }, { type: "class-poison", healingPenalty: 20, expiresTurn: 10 });
  heal(enemy, enemy);
  assert(hooks.hp(enemy) === 126, "The enemy multiplier stacks with healing bonuses and poison penalties");
  ({ enemy } = reset());
  enemy.character.currentHp = 990;
  heal(enemy, enemy);
  assert(hooks.hp(enemy) === 1000, "Healing is reduced before the HP cap, so a sufficient heal still fills the missing 10 HP");
  ({ enemy } = reset());
  heal(enemy, enemy, 4);
  assert(hooks.hp(enemy) === 100, "Small enemy heals round down without bypassing the reduction");
  heal(enemy, enemy, 5);
  assert(hooks.hp(enemy) === 101, "A 5-HP enemy heal restores 1 HP");
  hooks.applyEffects(enemy, enemy, [{ type: "restore-mana", amount: 100 }]);
  assert(enemy.character.currentMana === 200, "Mana restoration is unchanged");
  ({ enemy } = reset());
  enemy.effects.push({ type: "turn-start-restore-percent", hp: 10, mana: 10, expiresTurn: 10 });
  hooks.expire(enemy);
  assert(hooks.hp(enemy) === 120 && enemy.character.currentMana === 200, "Temporary regeneration reduces HP restoration but keeps Mana restoration");
  ({ enemy } = reset({ energist: 3 }));
  hooks.expire(enemy);
  assert(hooks.hp(enemy) === 106 && enemy.character.currentMana === 150, "Class passive regeneration is reduced");
  ({ enemy } = reset({}, "troll"));
  hooks.expire(enemy);
  assert(hooks.hp(enemy) === 110, `Racial regeneration is reduced (HP ${hooks.hp(enemy)}, race ${enemy.character.raceId})`);
  ({ enemy } = reset({ hero: 2 }));
  hooks.expire(enemy);
  assert(hooks.hp(enemy) === 110, "Team regeneration is reduced");
  ({ enemy } = reset({ vampire: 2 }));
  enemy.character.bloodSupplies = 1;
  hooks.expire(enemy);
  assert(hooks.hp(enemy) === 120 && enemy.character.bloodSupplies === 0, "Blood-supply regeneration is reduced and still consumes its supply");
  ({ enemy } = reset());
  const secondWind = itemCatalog.artifacts.find(item => item.effects?.some(effect => effect.kind === "low-hp-turn-start-heal-percent"));
  assert(secondWind, "A low-HP healing artifact is loaded");
  enemy.character.inventory.push(secondWind.id); enemy.character.equipment.artifact1 = secondWind.id;
  hooks.expire(enemy);
  assert(hooks.hp(enemy) === 110, "Artifact regeneration is reduced");
  ({ enemy, player } = reset());
  const weapon = getItem("weapon-forged-longsword-30-dwiro-rtoak-dwoak-s0");
  hooks.applyAttackHitEffects(enemy, player, weapon, 100, false, [{ onHitEffects: [{ type: "lifesteal-percent", amount: 50 }] }]);
  assert(hooks.hp(enemy) === 110, "Weapon skill life-steal is reduced");
  ({ enemy, player } = reset());
  currentHp = 900;
  hooks.applyEffects(enemy, player, [{ type: "damage", amount: 100, recipient: "target", lifeSteal: 1 }], 0, "basic", "Drain test", true);
  assert(hooks.hp(enemy) === 100 + Math.floor((900 - currentHp) / 5), "Spell life-steal restores 20% of damage dealt");
  ({ enemy, player } = reset());
  currentHp = 900;
  hooks.applyMeleeSpellEffects(enemy, player, [{ name: "Melee drain", key: "test-drain", amount: 100, element: "basic", lifeSteal: 1 }]);
  assert(hooks.hp(enemy) === 100 + Math.floor((900 - currentHp) / 5), "Melee spell life-steal is reduced");
  ({ enemy } = reset({ energist: 5 }));
  assert(hooks.useSkill(enemy, "energist:equilibrium"), "Equilibrium activates");
  assert(hooks.hp(enemy) === 140 && enemy.character.currentMana === 300, "Healing skills restore 20% of normal HP and normal Mana");
  ({ enemy } = reset({ "sanguine-medic": 5 }));
  enemy.character.currentHp = 800;
  const transfusionState = Combat.serialize();
  const ally = clone(transfusionState.actors.find(actor => actor.id === enemyId));
  ally.id = "enemy-healing-ally"; ally.character.classLevels = {}; ally.character.currentHp = 100;
  transfusionState.actors.push(ally); Combat.restore(transfusionState);
  enemy = hooks.actorById(enemyId);
  assert(hooks.useSkill(enemy, "sanguine-medic:blood-transfusion", hooks.actorById(ally.id)), "Blood Transfusion activates");
  assert(hooks.hp(enemy) === 650 && hooks.hp(hooks.actorById(ally.id)) === 160, "Blood Transfusion reduces recipient healing while preserving the caster's HP cost");
  ({ enemy, player } = reset());
  player.effects.push({ type: "turn-start-restore-percent", hp: 10, mana: 10, expiresTurn: 10 });
  hooks.expire(player);
  assert(currentHp === 200 && currentMana === 200, "Player regeneration retains its normal HP and Mana amounts");
  const friendlyState = Combat.serialize();
  const friendly = clone(enemyTemplate);
  friendly.id = "friendly-healing-test"; friendly.team = "player"; friendly.summoned = true;
  friendlyState.actors.push(friendly); Combat.restore(friendlyState);
  hooks.applyEffects(hooks.actorById("player"), hooks.actorById(friendly.id), [{ type: "heal", recipient: "target", amount: 100 }]);
  assert(hooks.hp(hooks.actorById(friendly.id)) === 200, "Allied summons retain normal healing");
  ({ enemy } = reset({ sharmat: 3 }));
  enemy.character.activeSkills["sharmat:lucid-change"] = { charges: 1 };
  assert(hooks.useSkill(enemy, "sharmat:lucid-change", enemy, null, true), "Lucid Change activates");
  assert(hooks.hp(enemy) === 280 && enemy.character.currentMana === 1000, "Full-resource restoration heals 20% of missing HP and full Mana");
  ({ enemy } = reset({ pactkeeper: 4 }));
  enemy.summoned = true;
  assert(hooks.useSkill(enemy, "pactkeeper:pact-renewal"), "Pact Renewal activates");
  assert(hooks.hp(enemy) === 150 && enemy.character.currentMana === 350, "Enemy summons also receive reduced healing");
  ({ enemy } = reset({ "soul-shepherd": 5 }));
  hooks.notifySummonLost({ summoned: true, summonerId: enemyId });
  assert(hooks.hp(enemy) === 110, "Summon-death restoration is reduced");
  ({ enemy } = reset());
  enemy.phaseTransitions = [{ name: "Healing phase", thresholdHpPercent: 50, healMaxHpPercent: 40 }];
  assert(hooks.startNextPhase(enemy) && hooks.hp(enemy) === 500, "Boss phase healing restores its full amount");
  heal(enemy, enemy);
  assert(hooks.hp(enemy) === 520, "Ordinary healing after a boss transition still receives the reduction");
  enemy.effects.push({ type: "turn-start-restore-percent", hp: 10, expiresTurn: 10 });
  hooks.expire(enemy);
  assert(hooks.hp(enemy) === 540, "Regeneration on the transition turn still receives the reduction");
  ({ enemy } = reset({ sharmat: 3 }));
  enemy.character.activeSkills["sharmat:lucid-change"] = { charges: 1 };
  enemy.phaseTransitions = [{ name: "Lucid phase", thresholdHpPercent: 50, healMaxHpPercent: 0, activateSkill: "sharmat:lucid-change" }];
  assert(hooks.startNextPhase(enemy) && hooks.hp(enemy) === 1000 && enemy.character.currentMana === 1000, "A transition-triggered restoration skill restores full HP and Mana");
  enemy.character.currentHp = 100;
  heal(enemy, enemy);
  assert(hooks.hp(enemy) === 120, "The restoration skill does not leave future healing exempt");
  ({ enemy } = reset());
  enemy.phaseTransitions = [{ name: "Invalid phase", thresholdHpPercent: 50, healMaxHpPercent: 0, activateSkill: "missing:skill" }];
  let failed = false;
  try { hooks.startNextPhase(enemy); }
  catch (error) { failed = error.message.includes("Boss phase skill could not activate"); }
  assert(failed, "Malformed transition test reaches the expected skill error");
  heal(enemy, enemy);
  assert(hooks.hp(enemy) === 120, "Even a failed transition restores the normal healing reduction");
  ({ enemy } = reset({ "vampire-lord": 3 }));
  enemy.character.currentHp = 5;
  enemy.skillExpiry["vampire-lord:blood-frenzy"] = enemy.turns + 1;
  hooks.expire(enemy);
  assert(hooks.hp(enemy) === 6, "A skill's resource reset cannot bypass the healing reduction");
  ({ enemy } = reset({ "vampire-lord": 3 }));
  enemy.character.currentHp = 100;
  enemy.skillExpiry["vampire-lord:blood-frenzy"] = enemy.turns + 1;
  hooks.expire(enemy);
  assert(hooks.hp(enemy) === 10, "HP losses are unchanged");
  ({ enemy } = reset({}, "undead"));
  enemy.character.currentHp = 0;
  const originalRandom = Math.random;
  try {
    Math.random = () => 0;
    assert(hooks.tryRaceDeathSave(enemy) && hooks.hp(enemy) === 1, "A death save still preserves 1 HP");
  } finally { Math.random = originalRandom; }
  ({ enemy, player } = reset());
  const spell = getSpell("mending-spring-water-support");
  const effect = [{ type: "heal", recipient: "target", amount: 100 }];
  const enemyForecast = hooks.evaluateSpellForTarget(enemy, spell, enemy, effect, 2, 0, 0);
  const playerForecast = hooks.evaluateSpellForTarget(player, spell, player, effect, 2, 0, 0);
  assert(enemyForecast.utility < playerForecast.utility, "AI forecasts value the reduced healing");
  const saved = Combat.serialize();
  Combat.restore(saved);
  enemy = hooks.actorById(enemyId);
  heal(enemy, enemy);
  assert(hooks.hp(enemy) === 120, "Existing and restored encounters use the reduction without a new save field");
  Combat.restore(null);
  delete window.__healingChecks;
}
