/* Run in a fresh browser profile after the app has loaded. */
async function runGuildChecks() {
  const $ = id => document.getElementById(id);
  const assert = (condition, label) => { if (!condition) throw new Error(label); };
  const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
  applyCharacter(normalizeCharacter(defaultCharacter()));
  WorldMap.setAmbientEnabled(false);
  $("map-open-button").click();
  assert(!$("map-guild").hidden, "Guild is available in Alderkeep");
  $("map-guild").click();
  // The Guild Rework (port task 2): the room's objects are the menu.
  const spot = kind => document.querySelector(`#guild-banner [data-guild-spot="${kind}"]`).dispatchEvent(new MouseEvent("click", { bubbles: true }));
  assert(!$("guild-modal").hidden && Number($("guild-reputation").textContent) === 0, "Guild opens with a separate Reputation balance");
  spot("tavern");
  assert(document.querySelectorAll("[data-guild-recruit]").length && [...document.querySelectorAll("[data-guild-recruit]")].every(button => button.disabled), "Recruits cannot be hired with an empty balance");
  spot("hooded");
  for (let i = 0; i < 100 && !$("guild-panel").querySelector('[data-guild-information-kind="class"]'); i++) await wait(10);
  assert($("guild-panel").querySelector('[data-guild-information-kind="class"]').disabled && $("guild-panel").querySelector('[data-guild-information-kind="item"]').disabled, "Information cannot be bought with an empty balance");
  spot("board");
  const board = Guild.boardFor(), standard = board.offers.filter(offer => offer.type !== "great-hunt");
  assert(standard.length === 4 && new Set(standard.map(offer => offer.type)).size === 4, "Four different quest types are on the board");
  const migrated = WorldRules.normalize({ guild: { quest: { type: "hunt", reward: { silver: 100, reputation: 11 } } } });
  assert(migrated.guild.quest.reward.reputation === 6 && WorldRules.normalize(migrated).guild.quest.reward.reputation === 6, "Saved quests are halved exactly once");
  document.querySelector("[data-guild-notice]").click();
  const firstIndex = Number(document.querySelector("[data-guild-notice].is-selected").dataset.guildNotice);
  $("guild-accept").click();
  assert(worldState.guild.quest && board.offers[firstIndex].taken && !document.querySelector(`[data-guild-notice="${firstIndex}"]`), "Taking a quest persists one active contract and removes its notice");
  const saved = normalizeCharacter(backupPayload().character);
  assert(saved.worldState.guild.quest?.type === worldState.guild.quest.type, "The active quest survives character save normalization");
  const reward = worldState.guild.quest.reward, startingMoney = ShopRules.walletValue(currencies);
  worldState.guild.quest.complete = true; worldState.guild.quest.progress = 1; worldState.guild.quest.originCastleId = "alderkeep";
  spot("counter");
  assert(!worldState.guild.quest && worldState.guild.reputation === reward.reputation, "Quest completion at the counter pays Reputation and clears the contract");
  assert(ShopRules.walletValue(currencies) === startingMoney + reward.silver, "Quest completion pays money");
  spot("board"); document.querySelector("[data-guild-notice]").click(); $("guild-accept").click();
  const originalConfirm = window.confirm;
  window.confirm = () => false;
  spot("board"); document.querySelector('[data-guild-give-up="quest"]').click();
  assert(worldState.guild.quest, "Declining give-up confirmation keeps the active quest");
  worldState.guild.quest = { version: 2, type: "hunt", zone: "Plains", enemy: "Goblin", point: { x: 1000, y: 500 }, regionId: "alder-vale", originRegionId: "alder-vale", originCastleId: "alderkeep", progress: 0, complete: false, reward };
  worldState.guild.avoidObjective = "hunt"; Guild.render();
  assert(Guild.markers().some(marker => marker.kind === "quest"), "The active Hunt has a map marker");
  window.confirm = () => true;
  const beforeGiveUpMoney = ShopRules.walletValue(currencies), beforeGiveUpReputation = worldState.guild.reputation;
  document.querySelector('[data-guild-give-up="quest"]').click();
  window.confirm = originalConfirm;
  assert(!worldState.guild.quest && !Guild.markers().some(marker => marker.kind === "quest") && worldState.guild.avoidObjective === null, "Giving up a quest removes its progress and map marker");
  assert(ShopRules.walletValue(currencies) === beforeGiveUpMoney && worldState.guild.reputation === beforeGiveUpReputation && !normalizeCharacter(backupPayload().character).worldState.guild.quest, "Giving up pays no reward and persists in the character save");
  assert(document.querySelector("[data-guild-notice]") && !$("guild-accept").disabled, "A new quest can be taken after giving up");

  worldState.guild.quest = { version: 2, type: "search", zone: "Plains", point: { x: 1000, y: 500 }, regionId: "alder-vale", originRegionId: "alder-vale", originCastleId: "alderkeep", progress: 0, complete: false, reward };
  $("guild-modal").querySelector("[data-guild-close]").click();
  WorldMap.render();
  document.querySelector(".map-guild-marker").dispatchEvent(new MouseEvent("click", { bubbles: true }));
  assert(WorldRules.distance(worldState.destination, worldState.guild.quest.point) < 1, "Clicking a Guild marker sets a travel destination");
  WorldMap.pause(); worldState.destination = null;
  worldState.position = { x: 1500, y: 800 }; WorldMap.render();
  assert($("map-search").hidden, "Search stays hidden elsewhere in the same broad zone");
  worldState.position = { x: 1000, y: 500 }; WorldMap.render();
  assert($("map-guild").hidden && !$("map-search").hidden, "Search appears only in its target zone, away from the castle");
  $("map-search").click();
  assert(!worldState.guild.quest.complete && worldState.pendingEncounter?.objective === "search", "Search starts the spot's fight instead of completing at once");
  worldState.pendingEncounter = null; $("map-encounter-modal").hidden = true; updateModalState();
  worldState.position = { x: 420, y: 490 }; WorldMap.render();
  worldState.guild.quest = null;

  level = 1;
  worldState.guild.reputation = 100;
  WorldMap.render(); $("map-guild").click(); Guild.render();
  const offerArtifacts = () => { spot("counter"); $("guild-artifacts").click(); };
  offerArtifacts();
  assert(worldState.guild.artifactOffers.length === 3 && new Set(worldState.guild.artifactOffers).size === 3, "Three different artifacts are offered");
  assert(worldState.guild.artifactOffers.every(id => getItem(id).rarity === "uncommon"), "Low-level Guild artifact offers use the nearest available rarity when Common artifacts do not exist");
  for (const [testLevel, rarity] of [[31, "rare"], [61, "epic"], [91, "legendary"]]) {
    level = testLevel;
    offerArtifacts();
    assert(worldState.guild.artifactOffers.every(id => getItem(id).rarity === rarity), `Level ${testLevel} Guild artifact offers are ${rarity}`);
  }
  level = 1;
  offerArtifacts();
  $("guild-panel").querySelector("[data-guild-artifact]").click();
  const challenge = structuredClone(worldState.guild.artifactChallenge);
  assert(challenge && worldState.guild.reputation === 30 && worldState.guild.artifactNextDay === 8, "Choosing an artifact spends 70 Reputation and starts a seven-day cooldown");
  const savedChallenge = normalizeCharacter(backupPayload().character).worldState.guild;
  assert(savedChallenge.artifactChallenge?.artifactId === challenge.artifactId && savedChallenge.artifactNextDay === 8 && savedChallenge.reputation === 30, "Artifact selection, cost, marker, and cooldown survive character saves");
  assert(WorldRules.zoneAt(challenge.point) === challenge.zone && Guild.markers().some(marker => marker.kind === "artifact"), "The empowered guardian is marked in a matching map zone");
  assert(!$("guild-artifacts") && $("guild-panel").textContent.includes(challenge.enemy), "Active challenge stays visible at the counter after selection");
  $("guild-modal").querySelector("[data-guild-close]").click();
  const normalEscape = await Combat.attemptTravelEscape([challenge.enemy], 25);
  const empoweredEscape = await Combat.attemptTravelEscape([challenge.enemy], 25, "artifact");
  assert(empoweredEscape.fastestEnemySpeed >= normalEscape.fastestEnemySpeed && empoweredEscape.chance <= normalEscape.chance, "Pre-combat Run accounts for the guardian's empowered Speed");
  worldState.position = { ...challenge.point }; WorldMap.render();
  assert(WorldMap.checkGuildObjective() && worldState.pendingEncounter.objective === "artifact", "Reaching the marked point opens the guardian prompt");
  assert($("map-encounter-enemies").textContent.includes("Empowered"), "The guardian is identified as empowered");
  $("map-encounter-fight").click();
  for (let i = 0; i < 50 && !Combat.active(); i++) await wait(20);
  assert(Combat.active(), "Fight starts the empowered guardian encounter");
  const actor = Combat.serialize().actors[1];
  assert(actor.name.startsWith("Empowered "), "Combat labels the guardian as empowered");
  const raw = await (await fetch("enemies/" + encodeURIComponent(challenge.enemy) + ".json")).json();
  assert(actor.empowered && actor.character.stats.strength === Math.floor(raw.stats.strength * 1.3), "Empowered guardian gains 30% base stats");
  const battle = Combat.serialize(); battle.actors[1].character.currentHp = 0;
  Combat.restore(battle); Combat.onSheetChange();
  for (let i = 0; i < 50 && Combat.active(); i++) await wait(20);
  assert(!Combat.active() && !inventory.includes(challenge.artifactId) && !worldState.guild.artifactChallenge && Combat.serialize().lootItems.includes(challenge.artifactId), "Defeating the guardian adds the chosen artifact to combat loot instead of inventory");
  assert(!$("combat-loot-modal").hidden && $("combat-loot-list").textContent.includes(getItem(challenge.artifactId).name), "The artifact is visibly listed among the dropped items");
  applyCharacter(normalizeCharacter(backupPayload().character));
  await wait(0);
  assert(!$("combat-loot-modal").hidden && Combat.serialize().lootItems.filter(id => id === challenge.artifactId).length === 1, "The pending artifact drop survives saving and restoring exactly once");
  $("combat-loot-keep").click();
  assert(inventory.filter(id => id === challenge.artifactId).length === 1 && Combat.serialize().lootResolved, "Keeping the loot adds the artifact to inventory exactly once");
  assert(Combat.serialize().experienceEarned >= Math.floor(CombatRules.enemyExperience(raw.level) * 1.2), "Empowered guardian awards boosted EXP");
  worldState.guild.artifactChallenge = { ...challenge };
  Combat.restore(null);
  assert(await Combat.startEncounter([challenge.enemy], "Artifact discard check", "artifact"), "A second artifact guardian encounter starts");
  const discardBattle = Combat.serialize();
  discardBattle.actors[1].character.currentHp = 0;
  Combat.restore(discardBattle); Combat.onSheetChange();
  for (let i = 0; i < 50 && Combat.active(); i++) await wait(20);
  assert(!$("combat-loot-modal").hidden && Combat.serialize().lootItems.includes(challenge.artifactId), "The second guardian's artifact is offered as loot");
  $("combat-loot-discard").click();
  assert(inventory.filter(id => id === challenge.artifactId).length === 1 && !worldState.guild.artifactChallenge, "Discarding the artifact does not add it to inventory and clears the completed challenge");
  worldState.guild.quest = { type: "hunt", enemy: challenge.enemy, zone: challenge.zone, point: challenge.point, progress: 0, complete: false, reward };
  $("map-open-button").click();
  WorldMap.render();
  assert(WorldMap.checkGuildObjective() && worldState.pendingEncounter.objective === "hunt", "Hunt quest spawns its marked empowered enemy");
  $("map-encounter-fight").click();
  for (let i = 0; i < 50 && !Combat.active(); i++) await wait(20);
  const huntBattle = Combat.serialize(); huntBattle.actors[1].character.currentHp = 0;
  Combat.restore(huntBattle); Combat.onSheetChange();
  for (let i = 0; i < 50 && Combat.active(); i++) await wait(20);
  assert(worldState.guild.quest.complete, "Defeating the marked empowered enemy completes the Hunt objective");
  $("combat-loot-discard").click();
  worldState.guild.quest = null;
  worldState.position = { x: 420, y: 490 }; WorldMap.render(); $("map-guild").click(); spot("counter");
  assert($("guild-artifacts").disabled, "Artifact service remains on cooldown after victory");
  worldState.guild.reputation = 70;
  advanceWorldTime(7 * 1440); spot("counter");
  assert(worldState.guild.artifactNextDay <= WorldRules.day(worldState.minutes) && !$("guild-artifacts").disabled, "Artifact service reopens after seven in-game days");
  $("guild-modal").querySelector("[data-guild-close]").click();
  worldState = WorldRules.normalize(); Combat.restore(null); WorldMap.resetView(); saveCharacter();
  return { passed: true };
}
