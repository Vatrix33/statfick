async function runNewClassChecks() {
  const assert = (condition, message) => { if (!condition) throw new Error(message); };
  const ids = ["archivist", "bounty-broker", "bulwark", "cartographer", "chronomancer", "courier", "drakeslayer", "dreamweaver", "echo-knight", "element-siphon", "fencer", "flagbearer", "gambit", "hexblade", "lifewarden", "mirror-mage", "nullblade", "pactkeeper", "pilgrim", "plaguebinder", "poisoner", "quartermaster", "reaver", "relic-warden", "riverstrider", "sanguine-medic", "scavenger", "soul-shepherd", "spellbreaker", "stormcaller", "sunstrider", "wildwarden"];
  for (const id of ids) {
    const definition = getClass(id);
    assert(definition, `${id} loaded`);
    assert(definition.levels.length === definition.maxLevel && definition.levels.every((rank, index) => rank.level === index + 1 && rank.description && rank.effects.length), `${id} has complete levels`);
    const effects = definition.levels.flatMap(rank => rank.effects);
    assert(effects.filter(effect => effect.type === "passive").length === 1 && effects.filter(effect => effect.type === "skill").length === 1, `${id} has one passive and one skill`);
    assert(effects.find(effect => effect.type === "skill").description && effects.find(effect => effect.type === "passive").description, `${id} describes its active features`);
  }
  assert(getClass("cartographer").maxLevel === 5, "Cartographer uses the documented five-level fallback");
  const character = defaultCharacter(); character.raceId = "human"; character.level = 65;
  character.classProgress = { oneHandedAttacks: 7, summonCasts: { "summon-juvenile-wolf": 10 }, lootEnemiesCollected: 30 };
  character.worldState.guild.completedQuests = 5;
  character.worldState.guild.completedTravelQuests = 15;
  applyCharacter(normalizeCharacter(character));
  assert(classProgress.oneHandedAttacks === 7 && classProgress.lootEnemiesCollected === 30 && worldState.guild.completedTravelQuests === 15, "new prerequisite counters survive normalization");
  assert(otherClassRequirementMet(getClass("bounty-broker")) && otherClassRequirementMet(getClass("courier")) && otherClassRequirementMet(getClass("fencer")) && otherClassRequirementMet(getClass("scavenger")), "tracked prerequisites become eligible");
  for (const id of ids) classLevels[id] = getClass(id).maxLevel;
  updateDerivedValues();
  const totals = calculateClassEffects();
  assert(ids.every(id => totals.skills.some(skill => skill.classId === id) && totals.passives.some(passive => passive.classId === id)), "all acquired skills and passives appear in their menus");
  renderClasses();
  assert(document.querySelector('[data-class-id="flagbearer"][data-class-color="blue"]') && document.querySelector('[data-class-id="stormcaller"][data-class-color="purple"]'), "class roster uses colors from class definitions");
  showClassDetails(getClass("stormcaller"));
  assert(document.querySelector('.class-detail[data-class-color="purple"]'), "class details use their definition color");
  assert(totals.riverSpeedFlat === 4 && totals.encounterChancePercent === -10 && totals.guildQuestChoiceFlat === 1, "regional travel and Guild effects are active");
  WorldMap.render();
  assert(document.getElementById("map-survey-bounds").children.length > 0, "Cartographer reveals zone boundaries");
  worldState.position = { x: 420, y: 490 };
  WorldMap.render();
  document.getElementById("map-guild").click();
  worldState.guild.boards = {};
  assert(Guild.boardFor().offers.filter(offer => offer.type !== "great-hunt").length === 5, "Bounty Broker adds a fifth quest to a castle guild's board");
  document.querySelector("[data-guild-close]").click();
  classLevels = { scavenger: 7 };
  activeSkills = {};
  const before = inventory.filter(id => id === "consumable-camping-supplies").length;
  activateSkill(calculateClassEffects().skills.find(skill => skill.id === "field-scrounge"));
  assert(inventory.filter(id => id === "consumable-camping-supplies").length === before + 1 && !activeSkills["scavenger:field-scrounge"].active, "Field Scrounge grants supplies once without leaving a toggle active");
  classLevels = { flagbearer: 4 };
  stats.speed = 150;
  currentHp = calculateMaxHpWithArtifacts(currentStats());
  updateDerivedValues();
  assert(await Combat.startEncounter(["Goblin"], "Flagbearer test"), "Flagbearer battle starts");
  const standardBattle = Combat.serialize();
  standardBattle.current = "player"; standardBattle.ap = 5;
  standardBattle.targetId = standardBattle.actors.find(actor => actor.team === "enemy").id;
  Combat.restore(standardBattle);
  const standardButton = document.querySelector('[data-skill="flagbearer:raise-standard"]');
  assert(standardButton && !standardButton.disabled, "Raise Standard is usable");
  standardButton.click();
  assert(Combat.serialize().actors.some(actor => actor.name === "Battle Standard" && actor.standardAura === 15), "Raise Standard creates a destructible aura unit");
  Combat.restore(null);
  classLevels = { pactkeeper: 3 };
  classProgress.summonCasts["summon-juvenile-wolf-nature-summon"] = 10;
  knownSpells = ["summon-juvenile-wolf-nature-summon"];
  currentHp = calculateMaxHpWithArtifacts(currentStats());
  updateDerivedValues();
  renderClasses();
  assert(document.querySelector('[data-class-id="pactkeeper"] .class-bind-button'), "Pactkeeper offers familiar binding in the class roster");
  assert(await Combat.startEncounter(["Goblin"], "Pactkeeper test"), "Pactkeeper battle starts");
  assert(Combat.serialize().actors.some(actor => actor.summoned && /Juvenile Wolf/i.test(actor.name)), "Bound Familiar returns at combat start");
  assert(classProgress.boundFamiliar?.spellId === "summon-juvenile-wolf-nature-summon", "Pactkeeper remembers its bound familiar");
  Combat.restore(null);
  classLevels = {};
  classProgress.oneHandedAttacks = 0;
  equipment.primaryHand = "weapon-forged-longsword-30-dwiro-rtoak-dwoak-s0";
  knownSpells = [];
  currentHp = calculateMaxHpWithArtifacts(currentStats());
  updateDerivedValues();
  assert(await Combat.startEncounter(["Goblin"], "Fencer progress test"), "One-handed weapon battle starts");
  assert(classProgress.oneHandedAttacks === 0, "Combat prediction does not count as a one-handed attack");
  const fencerBattle = Combat.serialize();
  fencerBattle.current = "player"; fencerBattle.ap = 5;
  fencerBattle.targetId = fencerBattle.actors.find(actor => actor.team === "enemy").id;
  Combat.restore(fencerBattle);
  assert(classProgress.oneHandedAttacks === 0, "Rendering a predicted attack does not count as an attack");
  document.querySelector('[data-action="attack"]').click();
  assert(classProgress.oneHandedAttacks === 1, "A real one-handed Attack action advances Fencer progress once");
  Combat.restore(null);
  return true;
}
