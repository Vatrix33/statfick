async function runSettingsCompanionChecks() {
  const $ = id => document.getElementById(id);
  const assert = (condition, message) => { if (!condition) throw Error(message); };
  const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
  Combat.restore(null);
  assert(GameSettings.state().battlePace === "fast" && GameSettings.state().combatAnimations, "Fast pace and animations are defaults");
  $("settings-open-button").click();
  $("battle-pace").value = "slow"; $("battle-pace").dispatchEvent(new Event("change"));
  $("combat-animations").click();
  assert(GameSettings.state().battlePace === "slow" && !GameSettings.state().combatAnimations && document.body.classList.contains("combat-animations-off"), "Settings controls apply both preferences");
  assert(JSON.parse(localStorage.getItem("stat-fick-game-settings")).battlePace === "slow", "Preferences persist outside character data");
  $("settings-modal").querySelector(".modal-close").click();
  const playerCharacter = defaultCharacter(); playerCharacter.level = 100; playerCharacter.raceId = "human";
  for (const key of Object.keys(playerCharacter.stats)) playerCharacter.stats[key] = 300;
  playerCharacter.currentHp = 100000; playerCharacter.currentMana = 100000;
  applyCharacter(normalizeCharacter(playerCharacter));
  assert(GameSettings.state().battlePace === "slow", "New characters do not reset preferences");
  const timers = [], originalTimeout = window.setTimeout;
  window.setTimeout = function(callback, delay, ...args) { if (callback.name === "enemyAction") timers.push(delay); return originalTimeout(callback, delay, ...args); };
  try {
    assert(await Combat.startEncounter(["Goblin"]), "Timing test combat starts");
    let battle = Combat.serialize(), goblin = battle.actors.find(actor => actor.team === "enemy");
    battle.current = goblin.id; battle.ap = 5; goblin.turnActionCount = 0;
    Combat.restore(battle); $("combat-view-toggle").click();
    assert(timers.at(-1) === 2400, "Slow enemy turn starts wait 2.4 seconds");
    const actionPoints = Combat.serialize().ap;
    await wait(1050);
    assert(Combat.serialize().ap === actionPoints, "Slow mode gives reading time before the enemy acts");
    battle = Combat.serialize(); battle.actors.find(actor => actor.id === goblin.id).turnActionCount = 1;
    Combat.restore(battle); $("combat-view-toggle").click(); GameSettings.setBattlePace("slow");
    assert(timers.at(-1) === 1800, "Slow actions wait 1.8 seconds");
    GameSettings.setBattlePace("fast"); assert(timers.at(-1) === 650, "Fast mode retains the old 650 ms delay");
    Combat.restore(null);
  } finally { window.setTimeout = originalTimeout; }
  const tierTen = spells.find(spell => spell.tier === 10);
  assert(!TierTenCinematics.play(tierTen), "Tier 10 animation is skipped while disabled");
  GameSettings.setCombatAnimations(true);
  assert(TierTenCinematics.play(tierTen), "Tier 10 animation can be enabled");
  GameSettings.setCombatAnimations(false);
  assert($("tier10-cinematic").hidden, "Disabling animations immediately dismisses a playing spell cinematic");
  assert(await Combat.startEncounter(["Ornn, God of the Forge"]), "Boss animation test starts");
  let battle = Combat.serialize(), boss = battle.actors.find(actor => actor.team === "enemy");
  boss.character.currentHp = Math.floor(boss.resourceMax.hp * .5);
  battle.current = null; battle.actors.forEach(actor => { actor.counter = actor.id === boss.id ? 1000 : 0; });
  Combat.restore(battle); Combat.onSheetChange(); await wait(50);
  battle = Combat.serialize(); boss = battle.actors.find(actor => actor.id === boss.id);
  assert(boss.phaseIndex === 1 && battle.actors.some(actor => actor.name.includes("Vulcanic Ram")), "Boss phase and summons still occur with animations disabled");
  assert($("boss-special-cinematic").hidden && !boss.phaseFlashUntil, "Disabled transitions create neither overlay nor animation delay");
  Combat.restore(null);
  const sword = getItem("weapon-forged-longsword-30-dwiro-rtoak-dwoak-s0");
  const armor = getItem("armor-forged-leather-armor-30-elraw-bbraw-hfraw-s0");
  const ring = items.find(item => item.id === "artifact-power-ring-artifact");
  assert(sword && armor && ring, "Equipment fixtures are loaded");
  showItemDetails(sword);
  assert(parseFloat(getComputedStyle($("inventory-modal").querySelector(".spell-detail-cost strong")).fontSize) <= parseFloat(getComputedStyle(document.documentElement).fontSize), "Inventory money prices have a compact font");
  applyCharacter(normalizeCharacter({ ...defaultCharacter(), raceId: "human", level: 60, perkPoints: 40, knownSpells: spells.filter(spell => spell.element === "nature").slice(0, 7).map(spell => spell.id) }));
  const offered = Companions.makeOffers()[0];
  offered.character = normalizeCharacter({ ...defaultCharacter(), raceId: "human", level: 30, stats: { ...defaultStats, speed: 90 }, perkPoints: 30, classLevels: { warrior: 5, rogue: 5 }, inventory: [sword.id, sword.id, armor.id, ring.id], equipment: { ...defaultEquipment, primaryHand: sword.id, armor: armor.id, artifact1: ring.id } });
  assert(Companions.add(offered), "Detailed sheet companion recruited");
  const member = companions[0]; Companions.open(member.id);
  const before = JSON.stringify({ knownSpells, perkPoints, trapsUsed, stats, classLevels });
  const classOptions = Combat.previewClassOptions(member.character);
  assert(JSON.stringify({ knownSpells, perkPoints, trapsUsed, stats, classLevels }) === before, "Companion previews never change main-character state");
  assert(classOptions.find(option => option.definition.id === "ambusher").met, "Highest-stat requirements use only basic stats, not HP");
  assert(!classOptions.find(option => option.definition.id === "beastmaster").met, "Companion requirements use their own spells, not the player's");
  assert($("companion-sheet").querySelectorAll(".companion-class-browser > section").length === 3, "Class browser has available, learned and detail columns");
  $("companion-sheet").querySelector('[data-comp-class-select="warrior"]').click();
  assert($("companion-sheet").querySelectorAll(".companion-class-detail .class-level-row").length === 5, "Class detail displays every level's features");
  const gear = $("companion-sheet").querySelector('[data-companion-equipment="primaryHand"]');
  assert(gear.textContent.includes("Hit chance") && gear.textContent.includes("Crit chance") && gear.textContent.includes("Primary scaling"), "Equipped weapons show complete calculated stats");
  assert($("companion-sheet").querySelector('[data-comp-current-stat="strength"]').closest(".companion-stat").querySelector(".companion-effective-bonus").textContent.includes("10"), "Permanent totals include item and class effects");
  $("companion-sheet").querySelector('[data-comp-browse-slot="offHand"]').click();
  assert($("companion-picker-list").querySelectorAll("[data-comp-picker-select]").length === 1 && $("companion-picker-list").textContent.includes("×2"), "Slot picker filters eligible items and groups duplicates by quantity");
  $("companion-picker-detail").querySelector('[data-comp-picker-action="equip"]').click();
  assert(member.character.equipment.offHand === sword.id && $("companion-picker-modal").hidden, "Detailed equipment picker equips a free copy");
  assert($("companion-sheet").querySelector(`[data-comp-take="${sword.id}"]`).disabled, "Transfers cannot remove an equipped copy and invalidate dual wielding");
  $("companion-sheet").querySelector('[data-comp-browse="inventory"]').click();
  $("companion-picker-search").value = sword.name; $("companion-picker-search").dispatchEvent(new Event("input", { bubbles: true }));
  assert($("companion-picker-list").querySelectorAll("button").length === 1, "Companion inventory is searchable");
  const search = $("companion-picker-search"), section = $("companion-section-training"); section.open = true;
  advanceWorldTime(60); Companions.render();
  assert(search === $("companion-picker-search") && !$("companion-picker-modal").hidden && section === $("companion-section-training") && section.open, "Background recovery preserves pickers and expanded sections");
  search.dispatchEvent(new KeyboardEvent("keydown", { key: "Escape", bubbles: true }));
  assert($("companion-picker-modal").hidden && !$("companions-modal").hidden, "Escape closes only the nested selection");
  $("companions-modal").querySelector(".modal-close").click();
  assert(await Combat.startEncounter(["Goblin"]), "Read-only companion inspection test starts");
  $("combat-sheet-button").click(); Companions.open(member.id);
  const live = Combat.serialize().actors.find(actor => actor.id === member.id);
  assert(Number($("companion-sheet").querySelector('[data-comp-resource="currentHp"]').max) === live.resourceMax.hp, "Combat sheets show frozen live resource maxima");
  $("companion-sheet").querySelector('[data-comp-browse-slot="armor"]').click();
  assert(!$("companion-picker-modal").hidden && $("companion-picker-detail").querySelector('[data-comp-picker-action="equip"]').disabled, "Full equipment details remain browsable but cannot be edited in combat");
  CompanionSheetDetails.close(); $("companions-modal").querySelector(".modal-close").click(); Combat.restore(null);
  GameSettings.setBattlePace("fast"); GameSettings.setCombatAnimations(true);
  Companions.open(member.id); $("companion-section-training").open = true;
  $("companion-section-training").scrollIntoView();
  await wait(700);
  return { passed: true, timing: "650 / 1800 / 2400 ms", companionColumns: 3 };
}
